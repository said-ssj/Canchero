BEGIN;

CREATE TABLE IF NOT EXISTS public.superadmin_audit_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id uuid NOT NULL,
    actor_name varchar(160) NOT NULL,
    actor_role varchar(40) NOT NULL,
    http_method varchar(10) NOT NULL,
    request_path varchar(500) NOT NULL,
    response_status integer NOT NULL,
    occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS superadmin_audit_event_occurred_idx
    ON public.superadmin_audit_event (occurred_at DESC);
CREATE INDEX IF NOT EXISTS superadmin_audit_event_actor_idx
    ON public.superadmin_audit_event (actor_user_id, occurred_at DESC);

ALTER TABLE public.superadmin_audit_event ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.superadmin_audit_event FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.superadmin_audit_event_id_seq FROM PUBLIC, anon, authenticated;

COMMIT;
