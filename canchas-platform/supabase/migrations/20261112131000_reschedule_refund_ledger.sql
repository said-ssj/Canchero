BEGIN;

CREATE TABLE public.devolucion_pago_reserva (
    id_devolucion bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva integer NOT NULL REFERENCES public.reserva(id_reserva) ON DELETE RESTRICT,
    monto numeric(10,2) NOT NULL CHECK (monto > 0),
    medio_pago varchar(80) NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'REGISTRADA', 'CANCELADA')),
    id_movimiento integer REFERENCES public.movimiento_caja(id_movimiento) ON DELETE RESTRICT,
    motivo varchar(200) NOT NULL,
    creado_en timestamp without time zone NOT NULL DEFAULT now(),
    usucre varchar(40),
    CONSTRAINT devolucion_pago_reserva_movimiento_estado_chk CHECK (
        (estado = 'REGISTRADA' AND id_movimiento IS NOT NULL)
        OR (estado <> 'REGISTRADA' AND id_movimiento IS NULL)
    )
);

CREATE INDEX devolucion_pago_reserva_reserva_fecha_idx
    ON public.devolucion_pago_reserva (id_reserva, creado_en DESC, id_devolucion DESC);
CREATE UNIQUE INDEX devolucion_pago_reserva_una_pendiente_idx
    ON public.devolucion_pago_reserva (id_reserva)
    WHERE estado = 'PENDIENTE';

ALTER TABLE public.devolucion_pago_reserva ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.devolucion_pago_reserva FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.devolucion_pago_reserva_id_devolucion_seq
    FROM PUBLIC, anon, authenticated;

COMMIT;
