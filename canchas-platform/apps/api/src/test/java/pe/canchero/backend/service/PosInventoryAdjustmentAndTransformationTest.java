package pe.canchero.backend.service;

import java.math.BigDecimal;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.web.server.ResponseStatusException;
import pe.canchero.backend.web.controller.PosController;
import pe.canchero.backend.web.dto.*;

import static org.junit.jupiter.api.Assertions.*;

class PosInventoryAdjustmentAndTransformationTest {
    private JdbcTemplate jdbc;
    private PosService posService;
    private VenueAccessService access;
    private PosController controller;
    private final AuthUserDto ownerA = new AuthUserDto("owner-a", "Owner A", "a@test.com", "999", "dueno");
    private final AuthUserDto ownerB = new AuthUserDto("owner-b", "Owner B", "b@test.com", "888", "dueno");

    @BeforeEach
    void setup() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1;MODE=PostgreSQL", "sa", ""));
        jdbc.execute("create table sede (id_sede int, id_dueno varchar, estado varchar)");
        jdbc.execute("create table categoria_producto (id_categoria int, nombre varchar, id_sede int, estado varchar)");
        jdbc.execute("create table producto (id_producto int, id_categoria int, codigo_barras varchar, nombre varchar, precio_compra numeric, precio_venta numeric, stock_minimo int, estado varchar, contenido numeric, unidad_medida varchar, descripcion varchar, foto_url varchar)");
        jdbc.execute("create table kardex (id_kardex int generated by default as identity primary key, id_producto int, id_sede int, id_tipo_mov_inv int, cantidad int, precio_unitario numeric, saldo_stock int, motivo varchar, fecha timestamp, feccre timestamp default current_timestamp, estado varchar, usucre varchar, pccre varchar)");
        jdbc.execute("create table caja (id_caja int, id_sede int, estado varchar)");
        jdbc.execute("create table sesion_caja (id_sesion_caja int, id_caja int, estado varchar, fecha_cierre timestamp)");

        jdbc.update("insert into sede values (1, 'owner-a', 'A'), (2, 'owner-b', 'A')");
        jdbc.update("insert into categoria_producto values (1, 'Bebidas', 1, 'A')");
        // Producto 10: Pack Gatorade x 6 (Costo 18.00, Venta 24.00, Stock inicial 10)
        jdbc.update("insert into producto values (10, 1, 'PACK-GAT', 'Pack Gatorade x 6', 18.00, 24.00, 2, 'A', 6, 'unid', 'Pack cerrado', null)");
        // Producto 11: Gatorade 500ml individual (Costo 3.00, Venta 5.00, Stock inicial 5)
        jdbc.update("insert into producto values (11, 1, 'GAT-500', 'Gatorade 500ml', 3.00, 5.00, 5, 'A', 500, 'ml', 'Botella suelta', null)");

        // Initial Kardex entries for Sede 1
        jdbc.update("insert into kardex (id_producto, id_sede, id_tipo_mov_inv, cantidad, precio_unitario, saldo_stock, motivo, fecha, estado) values (10, 1, 1, 10, 18.00, 10, 'Stock inicial', current_timestamp, 'A')");
        jdbc.update("insert into kardex (id_producto, id_sede, id_tipo_mov_inv, cantidad, precio_unitario, saldo_stock, motivo, fecha, estado) values (11, 1, 1, 5, 3.00, 5, 'Stock inicial', current_timestamp, 'A')");

        posService = new PosService(jdbc);
        access = new VenueAccessService(jdbc);
        controller = new PosController(posService, access);
    }

    @Test
    void negativeAdjustmentMermaDecrementsStockAndLogsKardex() {
        var req = new InventoryAdjustmentRequest(11, 1, "MERMA", 2, "Botella rota en heladera");
        var mov = posService.registerInventoryAdjustment(req);

        assertNotNull(mov);
        assertEquals("-", mov.tipo());
        assertEquals(2, mov.cantidad());
        assertEquals(3, mov.saldoStock()); // 5 - 2 = 3
        assertTrue(mov.motivo().contains("MERMA"));
        assertTrue(mov.motivo().contains("Botella rota en heladera"));

        // Verify latest stock
        var prods = posService.listProducts(1);
        var p11 = prods.stream().filter(p -> p.id() == 11).findFirst().orElseThrow();
        assertEquals(3, p11.stock());
    }

    @Test
    void negativeAdjustmentRejectsWhenStockInsufficient() {
        var req = new InventoryAdjustmentRequest(11, 1, "ROTURA", 10, "Demasiadas roturas");
        var ex = assertThrows(ResponseStatusException.class, () -> posService.registerInventoryAdjustment(req));
        assertEquals(409, ex.getStatusCode().value());
    }

    @Test
    void positiveAdjustmentSobranteIncrementsStock() {
        var req = new InventoryAdjustmentRequest(11, 1, "SOBRANTE", 4, "Aparecieron 4 botellas en conteo");
        var mov = posService.registerInventoryAdjustment(req);

        assertNotNull(mov);
        assertEquals("+", mov.tipo());
        assertEquals(4, mov.cantidad());
        assertEquals(9, mov.saldoStock()); // 5 + 4 = 9
        assertTrue(mov.motivo().contains("SOBRANTE"));
    }

    @Test
    void transformationFractionsPackIntoUnitsWithProportionalCost() {
        // Desarmar 2 packs de Gatorade x 6 (10 - 2 = 8 packs) -> Genera 12 botellas (5 + 12 = 17 botellas)
        // Costo pack = 18.00 * 2 = 36.00 / 12 = 3.00 unitario
        var req = new TransformationRequest(1, 10, 2, 11, 12, "Desarmar packs para venta por unidad");
        var res = posService.executeTransformation(req);

        assertEquals(10, res.productoOrigenId());
        assertEquals(2, res.cantidadOrigen());
        assertEquals(8, res.stockFinalOrigen());

        assertEquals(11, res.productoDestinoId());
        assertEquals(12, res.cantidadDestino());
        assertEquals(17, res.stockFinalDestino());
        assertEquals(3.00, res.costoUnitarioDestino(), 0.001);

        // Verify products stock
        var prods = posService.listProducts(1);
        assertEquals(8, prods.stream().filter(p -> p.id() == 10).findFirst().orElseThrow().stock());
        assertEquals(17, prods.stream().filter(p -> p.id() == 11).findFirst().orElseThrow().stock());

        // Verify Kardex movements logged
        var movements = posService.listInventoryMovements(1);
        assertTrue(movements.stream().anyMatch(m -> m.productoId() == 10 && "-".equals(m.tipo()) && m.cantidad() == 2 && m.motivo().contains("Transformación")));
        assertTrue(movements.stream().anyMatch(m -> m.productoId() == 11 && "+".equals(m.tipo()) && m.cantidad() == 12 && m.motivo().contains("Transformación")));
    }

    @Test
    void transformationRejectsSameProductOrInsufficientStock() {
        var sameProduct = new TransformationRequest(1, 10, 1, 10, 1, "Mismo");
        assertEquals(400, assertThrows(ResponseStatusException.class, () -> posService.executeTransformation(sameProduct)).getStatusCode().value());

        var insufficient = new TransformationRequest(1, 10, 50, 11, 300, "Mucho");
        assertEquals(409, assertThrows(ResponseStatusException.class, () -> posService.executeTransformation(insufficient)).getStatusCode().value());
    }

    @Test
    void inventorySummaryCalculatesValuationAndVelocityAlerts() {
        var summary = posService.getInventorySummary(1);

        assertNotNull(summary);
        assertEquals(1, summary.sedeId());
        assertEquals(2, summary.totalProductos());
        assertEquals(15, summary.totalUnidades()); // 10 packs + 5 botellas
        // Valorizado: 10 * 18.00 (180.00) + 5 * 3.00 (15.00) = 195.00
        assertEquals(new BigDecimal("195.00"), summary.totalValorizado());

        assertNotNull(summary.proyeccionesAgotamiento());
        assertEquals(2, summary.proyeccionesAgotamiento().size());
    }

    @Test
    void controllerEnforcesTenantIsolationForAdjustmentsAndTransformations() {
        var adj = new InventoryAdjustmentRequest(11, 1, "MERMA", 1, "Test");
        var trans = new TransformationRequest(1, 10, 1, 11, 6, "Test");

        // Owner B trying to adjust Sede 1 -> 403 Forbidden
        assertEquals(403, assertThrows(ResponseStatusException.class, () -> controller.inventoryAdjustment(adj, ownerB)).getStatusCode().value());
        assertEquals(403, assertThrows(ResponseStatusException.class, () -> controller.executeTransformation(trans, ownerB)).getStatusCode().value());
        assertEquals(403, assertThrows(ResponseStatusException.class, () -> controller.inventorySummary(1, ownerB)).getStatusCode().value());

        // Owner A allowed in Sede 1
        assertDoesNotThrow(() -> controller.inventoryAdjustment(adj, ownerA));
        assertDoesNotThrow(() -> controller.inventorySummary(1, ownerA));
    }
}
