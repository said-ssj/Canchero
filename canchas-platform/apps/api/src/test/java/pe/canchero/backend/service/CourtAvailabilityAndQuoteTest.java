package pe.canchero.backend.service;

import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.web.server.ResponseStatusException;
import pe.canchero.backend.web.dto.CourtAvailabilityResponse;
import pe.canchero.backend.web.dto.QuoteRequest;
import pe.canchero.backend.web.dto.QuoteResponse;

import static org.junit.jupiter.api.Assertions.*;

class CourtAvailabilityAndQuoteTest {

    private JdbcTemplate jdbc;
    private SupabaseDataService service;

    @BeforeEach
    void setup() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("create table sede (id_sede int primary key, nombre varchar(100), estado char(1))");
        jdbc.execute("create table tipo_cancha (id_tipo_cancha int primary key, nombre varchar(50), estado char(1))");
        jdbc.execute("""
                create table cancha (
                    id_cancha int primary key,
                    id_sede int,
                    id_tipo_cancha int,
                    nombre_numero varchar(100),
                    techada boolean,
                    foto_url varchar(255),
                    superficie varchar(80),
                    estado char(1)
                )
                """);
        jdbc.execute("""
                create table tipo_horario (
                    id_tipo_horario int generated by default as identity primary key,
                    id_sede int,
                    dia_semana int,
                    apertura time,
                    cierre time,
                    estado char(1)
                )
                """);
        jdbc.execute("""
                create table tarifa_cancha (
                    id_tarifa int generated by default as identity primary key,
                    id_cancha int,
                    dia_semana int,
                    hora_inicio time,
                    hora_fin time,
                    precio decimal(10,2),
                    estado char(1)
                )
                """);
        jdbc.execute("""
                create table bloqueo_mantenimiento (
                    id_bloqueo int generated by default as identity primary key,
                    id_cancha int,
                    motivo varchar(200),
                    fecha_inicio timestamp,
                    fecha_fin timestamp,
                    estado char(1)
                )
                """);
        jdbc.execute("""
                create table estado_reserva (
                    id_estado_reserva int primary key,
                    nombre varchar(50),
                    estado char(1)
                )
                """);
        jdbc.execute("""
                create table reserva (
                    id_reserva int generated by default as identity primary key,
                    id_cancha int,
                    id_estado_reserva int,
                    codigo_pase varchar(30),
                    fecha_reserva date,
                    hora_inicio time,
                    hora_fin time,
                    monto_total decimal(10,2),
                    estado char(1)
                )
                """);

        jdbc.update("insert into sede values (10, 'Sede Norte', 'A'), (20, 'Sede Sur', 'A')");
        jdbc.update("insert into tipo_cancha values (1, 'Fútbol 7', 'A')");
        // Ambas sedes tienen una cancha llamada 'Cancha 1'
        jdbc.update("insert into cancha values (101, 10, 1, 'Cancha 1', true, null, 'Grass Sintético', 'A')");
        jdbc.update("insert into cancha values (202, 20, 1, 'Cancha 1', false, null, 'Grass Sintético', 'A')");

        // Horario jueves (dia_semana = 4) para Sede Norte: 08:00 a 23:00
        jdbc.update("insert into tipo_horario (id_sede, dia_semana, apertura, cierre, estado) values (10, 4, '08:00:00', '23:00:00', 'A')");

        // Tarifas diferenciadas por tramo para Cancha 101 en jueves (dia_semana = 4): día 90, noche (desde 18:00) 120
        jdbc.update("insert into tarifa_cancha (id_cancha, dia_semana, hora_inicio, hora_fin, precio, estado) values (101, 4, '08:00:00', '18:00:00', 90.00, 'A')");
        jdbc.update("insert into tarifa_cancha (id_cancha, dia_semana, hora_inicio, hora_fin, precio, estado) values (101, 4, '18:00:00', '00:00:00', 120.00, 'A')");

        jdbc.update("insert into estado_reserva values (1, 'Pendiente', 'A'), (2, 'Confirmada', 'A'), (4, 'Cancelada', 'A')");

        // Reserva confirmada en Cancha 101 y otra en Cancha 202 (mismo nombre 'Cancha 1')
        jdbc.update("insert into reserva (id_cancha, id_estado_reserva, codigo_pase, fecha_reserva, hora_inicio, hora_fin, monto_total, estado) values (101, 2, '#CAN-1111', '2026-10-22', '18:00:00', '20:00:00', 240.00, 'A')");
        jdbc.update("insert into reserva (id_cancha, id_estado_reserva, codigo_pase, fecha_reserva, hora_inicio, hora_fin, monto_total, estado) values (101, 4, '#CAN-2222', '2026-10-22', '20:00:00', '21:00:00', 120.00, 'A')");
        jdbc.update("insert into reserva (id_cancha, id_estado_reserva, codigo_pase, fecha_reserva, hora_inicio, hora_fin, monto_total, estado) values (202, 2, '#CAN-3333', '2026-10-22', '16:00:00', '18:00:00', 280.00, 'A')");

        service = new SupabaseDataService(jdbc, null);
    }

    @Test
    void availabilityIsolatesByExactCourtIdAndExcludesCancelledBookings() {
        CourtAvailabilityResponse avail = service.getCourtAvailability("101", "2026-10-19", "2026-10-25");
        assertEquals("101", avail.courtId());
        assertEquals("10", avail.venueId());
        assertEquals(1, avail.ocupaciones().size());
        assertEquals(101, avail.ocupaciones().get(0).idCancha());
        assertEquals("2026-10-22", avail.ocupaciones().get(0).fechaReserva());
        assertEquals("18:00", avail.ocupaciones().get(0).horaInicio());
        assertEquals("20:00", avail.ocupaciones().get(0).horaFin());
    }

    @Test
    void quoteCalculatesMixedDayAndNightTranchesAndRejectsGaps() {
        // 2026-10-22 es jueves (dia_semana = 4). Seleccionamos 19:00 y 17:00 y 18:00 desordenados
        QuoteResponse quote = service.quoteCourtBooking("101", new QuoteRequest("2026-10-22", List.of(19, 17, 18)));
        assertTrue(quote.valid());
        assertEquals("17:00", quote.timeStart());
        assertEquals("20:00", quote.timeEnd());
        assertEquals("17:00 - 20:00", quote.displayRange());
        assertEquals(3, quote.durationHours());
        assertEquals(3, quote.tranches().size());
        assertEquals(90.0, quote.tranches().get(0).price());
        assertFalse(quote.tranches().get(0).isNight());
        assertEquals(120.0, quote.tranches().get(1).price());
        assertTrue(quote.tranches().get(1).isNight());
        assertEquals(330.0, quote.subtotal());
        assertEquals(330.0, quote.total());

        // Con hueco entre 18:00 y 20:00
        QuoteResponse gapQuote = service.quoteCourtBooking("101", new QuoteRequest("2026-10-22", List.of(18, 20)));
        assertFalse(gapQuote.valid());
        assertTrue(gapQuote.errorMessage().contains("Existe un hueco no seleccionado"));

        // Medianoche 22:00 y 23:00 -> termina a las 00:00
        QuoteResponse midnightQuote = service.quoteCourtBooking("101", new QuoteRequest("2026-10-22", List.of(22, 23)));
        assertTrue(midnightQuote.valid());
        assertEquals("22:00", midnightQuote.timeStart());
        assertEquals("00:00", midnightQuote.timeEnd());
        assertEquals("22:00 - 00:00", midnightQuote.displayRange());
    }

    @Test
    void rejectsNonExistentCourtInAvailabilityAndQuote() {
        assertThrows(ResponseStatusException.class,
                () -> service.getCourtAvailability("999", "2026-10-19", "2026-10-25"));
        assertThrows(ResponseStatusException.class,
                () -> service.quoteCourtBooking("999", new QuoteRequest("2026-10-22", List.of(18))));
    }
}
