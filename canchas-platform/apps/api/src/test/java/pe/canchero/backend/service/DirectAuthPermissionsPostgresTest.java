package pe.canchero.backend.service;

import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import pe.canchero.backend.it.PostgresTestServer;
import java.nio.file.*;
import static org.junit.jupiter.api.Assertions.*;

class DirectAuthPermissionsPostgresTest {
    @Test void closesTableAndColumnGrantsWithoutDeletingAccounts() throws Exception {
        PostgresTestServer.requireAvailable();
        PostgresTestServer.resetSchema();
        var jdbc = new JdbcTemplate(PostgresTestServer.dataSource());
        jdbc.execute("""
            DO $$ BEGIN
              IF NOT EXISTS(select 1 from pg_roles where rolname='anon') THEN CREATE ROLE anon; END IF;
              IF NOT EXISTS(select 1 from pg_roles where rolname='authenticated') THEN CREATE ROLE authenticated; END IF;
            END $$;
            CREATE TABLE IF NOT EXISTS public.proveedor(id integer generated by default as identity);
            CREATE TABLE IF NOT EXISTS public.compra(id integer generated by default as identity);
            CREATE TABLE IF NOT EXISTS public.compra_detalle(id integer generated by default as identity);
            CREATE TABLE IF NOT EXISTS public.reporte_cancha(id integer generated by default as identity);
            GRANT SELECT ON public.usuario TO PUBLIC;
            GRANT SELECT(password_hash) ON public.usuario TO anon;
            GRANT ALL ON public.compra, public.compra_detalle, public.proveedor, public.reporte_cancha TO authenticated;
            CREATE POLICY compra_auth_policy ON public.compra FOR ALL TO authenticated USING(true) WITH CHECK(true);
            """);
        long count = jdbc.queryForObject("select count(*) from public.usuario", Long.class);
        Path root = Path.of(System.getProperty("user.dir")).toAbsolutePath();
        while (root != null && !Files.isDirectory(root.resolve("supabase/migrations"))) root = root.getParent();
        assertNotNull(root);
        String sql = Files.readString(root.resolve("supabase/migrations/20261111234627_restringir_acceso_directo_cuentas_compras.sql"));
        jdbc.execute(sql);
        jdbc.execute(sql); // Reejecución segura.
        for (String role : new String[]{"anon", "authenticated"}) {
            for (String table : new String[]{"usuario", "compra", "compra_detalle", "proveedor", "reporte_cancha"}) {
                assertFalse(jdbc.queryForObject("select has_table_privilege(?,?,'SELECT,INSERT,UPDATE,DELETE')",
                        Boolean.class, role, "public." + table));
            }
            assertFalse(jdbc.queryForObject("select has_column_privilege(?,'public.usuario','password_hash','SELECT')",
                    Boolean.class, role));
        }
        assertEquals(count, jdbc.queryForObject("select count(*) from public.usuario", Long.class));
    }
}
