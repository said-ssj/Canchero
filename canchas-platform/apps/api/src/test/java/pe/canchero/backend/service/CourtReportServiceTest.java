package pe.canchero.backend.service;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.web.server.ResponseStatusException;
import pe.canchero.backend.web.dto.AuthUserDto;
import pe.canchero.backend.web.dto.CourtReportRequest;
import pe.canchero.backend.web.dto.CourtReportResponse;
import pe.canchero.backend.web.dto.UpdateCourtReportStatusRequest;

import java.util.List;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

class CourtReportServiceTest {

    private JdbcTemplate jdbc;
    private CourtReportService service;

    private final UUID ownerAUuid = UUID.randomUUID();
    private final UUID ownerBUuid = UUID.randomUUID();
    private final UUID playerUuid = UUID.randomUUID();
    private final UUID adminUuid = UUID.randomUUID();

    private AuthUserDto ownerA;
    private AuthUserDto ownerB;
    private AuthUserDto player;
    private AuthUserDto admin;

    @BeforeEach
    void setup() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1;MODE=PostgreSQL", "sa", ""));

        // Setup minimal schema
        jdbc.execute("create table rol (id_rol int primary key, nombre varchar(50), estado char(1))");
        jdbc.execute("""
                create table usuario (
                    id_usuario uuid primary key,
                    id_rol int,
                    nombre varchar(120),
                    correo varchar(150),
                    password_hash varchar(200),
                    estado char(1)
                )""");
        jdbc.execute("""
                create table sede (
                    id_sede int primary key,
                    id_dueno uuid,
                    nombre varchar(120),
                    estado char(1)
                )""");
        jdbc.execute("""
                create table cancha (
                    id_cancha int primary key,
                    id_sede int,
                    nombre_numero varchar(100),
                    estado char(1)
                )""");
        jdbc.execute("""
                create table reporte_cancha (
                    id_reporte int generated by default as identity primary key,
                    id_cancha int,
                    id_sede int,
                    id_usuario uuid,
                    tipo_problema varchar(50),
                    descripcion text,
                    estado varchar(20) default 'PENDIENTE',
                    prioridad varchar(20) default 'MEDIA',
                    resolucion text,
                    fecha_resolucion timestamp,
                    id_usuario_resolucion uuid,
                    fecha_creacion timestamp default current_timestamp,
                    usucre varchar(40),
                    pccre varchar(40),
                    feccre timestamp default current_timestamp,
                    usmod varchar(40),
                    pcmod varchar(40),
                    fecmod timestamp
                )""");

        jdbc.update("insert into rol values (1, 'cliente', 'A'), (2, 'dueno', 'A'), (3, 'superadmin', 'A')");
        jdbc.update("insert into usuario values (?, 2, 'Dueño A', 'duenoA@canchero.pe', 'hash', 'A')", ownerAUuid);
        jdbc.update("insert into usuario values (?, 2, 'Dueño B', 'duenoB@canchero.pe', 'hash', 'A')", ownerBUuid);
        jdbc.update("insert into usuario values (?, 1, 'Jugador Test', 'jugador@canchero.pe', 'hash', 'A')", playerUuid);
        jdbc.update("insert into usuario values (?, 3, 'Admin Global', 'admin@canchero.pe', 'hash', 'A')", adminUuid);

        ownerA = new AuthUserDto(ownerAUuid.toString(), "Dueño A", "duenoA@canchero.pe", "900000001", "dueno");
        ownerB = new AuthUserDto(ownerBUuid.toString(), "Dueño B", "duenoB@canchero.pe", "900000002", "dueno");
        player = new AuthUserDto(playerUuid.toString(), "Jugador Test", "jugador@canchero.pe", "900000003", "cliente");
        admin = new AuthUserDto(adminUuid.toString(), "Admin Global", "admin@canchero.pe", "900000004", "superadmin");

        // Sede 10 tiene 2 canchas (101 y 102); Sede 20 tiene 1 cancha (201)
        jdbc.update("insert into sede values (10, ?, 'Complejo San Isidro', 'A')", ownerAUuid);
        jdbc.update("insert into sede values (20, ?, 'Complejo Miraflores', 'A')", ownerBUuid);
        StaffTestSchema.create(jdbc);
        jdbc.update("insert into cancha values (101, 10, 'Cancha Sintética 1', 'A')");
        jdbc.update("insert into cancha values (102, 10, 'Cancha Sintética 2', 'A')");
        jdbc.update("insert into cancha values (201, 20, 'Cancha Pádel 1', 'A')");

        VenueAccessService venueAccess = new VenueAccessService(jdbc);
        service = new CourtReportService(jdbc, venueAccess);
    }

    @Test
    void playerReportsCourtAndVenueAutomaticallyReceivesIt() {
        CourtReportRequest req = new CourtReportRequest(101, "ILUMINACION", "Reflector izquierdo parpadea constantemente", "ALTA");
        CourtReportResponse created = service.createReport(req, player);

        assertNotNull(created);
        assertTrue(created.id() > 0);
        assertEquals(101, created.canchaId());
        assertEquals("Cancha Sintética 1", created.nombreCancha());
        assertEquals(10, created.sedeId());
        assertEquals("Complejo San Isidro", created.nombreSede());
        assertEquals("PENDIENTE", created.estado());
        assertEquals("ALTA", created.prioridad());
        assertEquals("Reflector izquierdo parpadea constantemente", created.descripcion());

        // El dueño de la sede 10 lista los reportes de su sede y encuentra el reporte
        List<CourtReportResponse> venueReports = service.listReportsByVenue(10, ownerA);
        assertEquals(1, venueReports.size());
        assertEquals(created.id(), venueReports.get(0).id());
    }

    @Test
    void venueCanHaveMultipleReportsFromDifferentCourts() {
        // Reporte para cancha 101
        service.createReport(new CourtReportRequest(101, "ILUMINACION", "Luz quemada en arco norte", "MEDIA"), player);
        // Reporte para cancha 102
        service.createReport(new CourtReportRequest(102, "ESTADO_CESPED", "Hueco en el área penal", "ALTA"), player);

        List<CourtReportResponse> venueReports = service.listReportsByVenue(10, ownerA);
        assertEquals(2, venueReports.size());

        // Verificamos que contenga ambas canchas
        assertTrue(venueReports.stream().anyMatch(r -> r.canchaId() == 101 && r.tipoProblema().equals("ILUMINACION")));
        assertTrue(venueReports.stream().anyMatch(r -> r.canchaId() == 102 && r.tipoProblema().equals("ESTADO_CESPED")));
    }

    @Test
    void venueOwnerCannotViewReportsOfAnotherOwnerVenue() {
        service.createReport(new CourtReportRequest(101, "LIMPIEZA", "Botellas vacías en la banca", "BAJA"), player);

        // Dueño B intenta acceder a los reportes de Sede 10 (pertenece a Dueño A) -> 403 Forbidden
        ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                service.listReportsByVenue(10, ownerB));
        assertEquals(403, ex.getStatusCode().value());
    }

    @Test
    void adminCanViewReportsOfAnyVenue() {
        service.createReport(new CourtReportRequest(101, "REDES_ARCOS", "Red rota en el arco", "MEDIA"), player);

        // Admin lista reportes de la Sede 10
        List<CourtReportResponse> reports = service.listReportsByVenue(10, admin);
        assertEquals(1, reports.size());
    }

    @Test
    void venueOwnerCanUpdateReportStatusToResolved() {
        CourtReportResponse created = service.createReport(
                new CourtReportRequest(101, "ILUMINACION", "Foco fundido", "ALTA"), player);

        UpdateCourtReportStatusRequest updateReq = new UpdateCourtReportStatusRequest(
                "RESUELTO", "Se reemplazó el foco LED por uno nuevo.");
        CourtReportResponse updated = service.updateStatus(created.id(), updateReq, ownerA);

        assertEquals("RESUELTO", updated.estado());
        assertEquals("Se reemplazó el foco LED por uno nuevo.", updated.resolucion());
        assertNotNull(updated.fechaResolucion());
    }

    @Test
    void playerCanListHisOwnReports() {
        service.createReport(new CourtReportRequest(101, "OTRO", "Falta inflador de pelotas", "BAJA"), player);
        service.createReport(new CourtReportRequest(201, "ILUMINACION", "Luz tenue", "MEDIA"), player);

        List<CourtReportResponse> myReports = service.listMyReports(player);
        assertEquals(2, myReports.size());
    }

    @Test
    void rejectsInvalidCourtOrShortDescription() {
        assertThrows(ResponseStatusException.class, () ->
                service.createReport(new CourtReportRequest(999, "ILUMINACION", "Cancha inexistente", "MEDIA"), player));

        assertThrows(ResponseStatusException.class, () ->
                service.createReport(new CourtReportRequest(101, "ILUMINACION", "ab", "MEDIA"), player));
    }
}

