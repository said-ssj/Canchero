package pe.canchero.backend.service;

import java.time.LocalTime;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import java.util.stream.IntStream;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.web.server.ResponseStatusException;
import pe.canchero.backend.service.VenueHoursService.DayHours;
import pe.canchero.backend.web.dto.AuthUserDto;
import static org.junit.jupiter.api.Assertions.*;

class VenueHoursServiceTest {
    private JdbcTemplate jdbc;
    private VenueHoursService service;
    private final AuthUserDto owner = new AuthUserDto("owner-1", "", "", "", "dueno");

    @BeforeEach
    void setup() {
        jdbc = new JdbcTemplate(new DriverManagerDataSource(
                "jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", ""));
        jdbc.execute("create table sede (id_sede int primary key, id_dueno varchar(40))");
        jdbc.execute("""
                create table tipo_horario (
                id_tipo_horario int generated by default as identity primary key,
                id_sede int references sede(id_sede), dia_semana int,
                apertura time, cierre time, estado char(1), usucre varchar(30), pccre varchar(30))
                """);
        jdbc.update("insert into sede values (1, 'owner-1'), (2, 'owner-2')");
        service = new VenueHoursService(jdbc);
    }

    private List<DayHours> week() {
        return IntStream.range(0, 7).mapToObj(day ->
                new DayHours(day, LocalTime.of(6, 0), LocalTime.of(23, 0), day != 0)).toList();
    }

    @Test
    void savesAndReloadsWeekWithClosedDay() {
        service.save(1, owner, week());
        assertEquals(week(), new VenueHoursService(jdbc).list(1));
    }

    @Test
    void repeatedSaveDoesNotDuplicateOrChangeOtherVenue() {
        service.save(2, new AuthUserDto("owner-2", "", "", "", "dueno"), week());
        service.save(1, owner, week());
        service.save(1, owner, week());
        assertEquals(7, service.list(1).size());
        assertEquals(week(), service.list(2));
    }

    @Test
    void rejectsAnotherOwnerBeforeWriting() {
        var error = assertThrows(ResponseStatusException.class, () -> service.save(2, owner, week()));
        assertEquals(403, error.getStatusCode().value());
        assertTrue(service.list(2).isEmpty());
    }

    @Test
    void rejectsMissingOrDuplicateDaysAndEqualHours() {
        assertThrows(ResponseStatusException.class, () -> service.save(1, owner, week().subList(0, 6)));
        var days = new ArrayList<>(week());
        days.set(6, days.get(0));
        assertThrows(ResponseStatusException.class, () -> service.save(1, owner, days));
        days.set(6, new DayHours(6, LocalTime.NOON, LocalTime.NOON, true));
        assertThrows(ResponseStatusException.class, () -> service.save(1, owner, days));
        assertTrue(service.list(1).isEmpty());
    }

    @Test
    void supportsOvernightClosing() {
        var days = new ArrayList<>(week());
        days.set(6, new DayHours(6, LocalTime.of(18, 0), LocalTime.of(2, 0), true));
        service.save(1, owner, days);
        assertEquals(days, service.list(1));
    }
}
