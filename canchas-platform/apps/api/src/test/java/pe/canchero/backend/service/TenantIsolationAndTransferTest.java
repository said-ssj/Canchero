    @Test
    void productCatalogIsStrictlyIsolatedByVenueKardex() {
        // Sede 1 solo ve Producto 1 (con stock 20). No ve Producto 2 (de Sede 3).
        List<PosCatalogService.ProductDetail> sede1Prods = catalogService.listProducts(1, ownerA, "TODOS", null, null);
        assertEquals(1, sede1Prods.size());
        assertEquals("Agua Mineral 500ml", sede1Prods.get(0).nombre());
        assertEquals(20, sede1Prods.get(0).stock());

        // Sede 2 pertenece al mismo dueño pero no tiene kardex para Producto 1 aún. Debe retornar lista vacía.
        List<PosCatalogService.ProductDetail> sede2Prods = catalogService.listProducts(2, ownerA, "TODOS", null, null);
        assertTrue(sede2Prods.isEmpty(), "Sede 2 no debe ver productos sin kardex en su sede");

        // En categorías, el conteo totalProductos para Sede 1 debe ser 1, y para Sede 2 debe ser 0
        var catSede1 = catalogService.categories(1, ownerA);
        assertEquals(1, catSede1.get(0).totalProductos());

        var catSede2 = catalogService.categories(2, ownerA);
        assertEquals(0, catSede2.get(0).totalProductos());
    }

    @Test
    void cannotUpdateOrToggleProductNotInVenueInventory() {
        // Intento de actualizar producto 2 (que no está en inventario de Sede 1) desde Sede 1
        PosCatalogService.ProductRequest updateReq = new PosCatalogService.ProductRequest(
                1, 1, "Hack Nombre", "775002", "Desc", BigDecimal.valueOf(500), "ml",
                BigDecimal.valueOf(1.0), BigDecimal.valueOf(3.0), 0, 5, ""
        );
        ResponseStatusException exUpdate = assertThrows(ResponseStatusException.class, () ->
                catalogService.updateProduct(2, updateReq, ownerA));
        assertTrue(exUpdate.getMessage().contains("no pertenece al inventario de esta sede"));

        // Intento de toggle estado producto 2 desde Sede 1
        ResponseStatusException exToggle = assertThrows(ResponseStatusException.class, () ->
                catalogService.toggleProductStatus(2, 1, ownerA));
        assertTrue(exToggle.getMessage().contains("no pertenece al inventario de esta sede"));
    }

    @Test
    void transferBetweenVenuesOfSameOwnerSucceedsAndUpdatesKardex() {
        // Traslado de 5 unidades de Producto 1 desde Sede 1 hacia Sede 2 (ambas del Dueño A)
        InventoryTransferRequest req = new InventoryTransferRequest(1, 2, 1, 5, "Envío a sucursal Norte");
        InventoryTransferResultDto result = posController.transferInventory(req, ownerA);

        assertNotNull(result);
        assertEquals(1, result.sourceSedeId());
        assertEquals(2, result.targetSedeId());
        assertEquals(15, result.stockOrigenFinal(), "Stock en sede origen debe descontarse a 15");
        assertEquals(5, result.stockDestinoFinal(), "Stock en sede destino debe incrementarse a 5");

        // Ahora Sede 2 tiene Producto 1 en su catálogo
        List<PosCatalogService.ProductDetail> sede2Prods = catalogService.listProducts(2, ownerA, "TODOS", null, null);
        assertEquals(1, sede2Prods.size());
        assertEquals(5, sede2Prods.get(0).stock());

        // Y Sede 1 tiene 15
        List<PosCatalogService.ProductDetail> sede1Prods = catalogService.listProducts(1, ownerA, "TODOS", null, null);
        assertEquals(15, sede1Prods.get(0).stock());
    }

    @Test
    void transferBetweenVenuesOfDifferentOwnersIsForbidden() {
        // Dueño A intenta trasladar mercadería hacia Sede 3 (Dueño B)
        InventoryTransferRequest req = new InventoryTransferRequest(1, 3, 1, 5, "Intento ilegal");

        ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                posController.transferInventory(req, ownerA));
        assertTrue(ex.getStatusCode().value() == 403 || ex.getStatusCode().value() == 404);

        // Verificar que no se descontó nada de Sede 1
        List<PosCatalogService.ProductDetail> sede1Prods = catalogService.listProducts(1, ownerA, "TODOS", null, null);
        assertEquals(20, sede1Prods.get(0).stock());
    }

    @Test
    void courtListingsWithoutVenueIdAreScopedToUserAuthorizedVenues() {
        // Dueño A consulta canchas sin enviar venueId
        var resOwnerA = courtController.list(null, ownerA);
        assertEquals(200, resOwnerA.getStatusCode().value());
        List<CourtDto> courtsA = resOwnerA.getBody();
        assertNotNull(courtsA);
        assertEquals(2, courtsA.size(), "Dueño A solo debe ver las canchas de sus sedes (1 y 2)");
        assertTrue(courtsA.stream().anyMatch(c -> c.id().equals("101")));
        assertTrue(courtsA.stream().anyMatch(c -> c.id().equals("102")));
        assertFalse(courtsA.stream().anyMatch(c -> c.id().equals("103")), "No debe ver la cancha de Sede 3 (Dueño B)");

        // Usuario anónimo sin venueId debe recibir lista vacía
        var resAnon = courtController.list(null, null);
        assertEquals(200, resAnon.getStatusCode().value());
        assertTrue(resAnon.getBody().isEmpty(), "Usuario anónimo sin venueId no debe recibir canchas globales");
    }

    @Test
    void cannotMoveCourtToAnotherOwnersVenue() {
        // Dueño A intenta mover su cancha 101 a Sede 3 (Dueño B)
        CourtRequest moveReq = new CourtRequest("3", "Cancha Movida", "Fútbol 7", "Gras", "", null, true, true, 50.0);

        ResponseStatusException ex = assertThrows(ResponseStatusException.class, () ->
                courtController.update(101, ownerA, moveReq));
        assertTrue(ex.getStatusCode().value() == 403 || ex.getStatusCode().value() == 404);

        // La cancha sigue perteneciendo a Sede 1
        Integer sedeActual = jdbc.queryForObject("select id_sede from cancha where id_cancha = 101", Integer.class);
        assertEquals(1, sedeActual);
    }
