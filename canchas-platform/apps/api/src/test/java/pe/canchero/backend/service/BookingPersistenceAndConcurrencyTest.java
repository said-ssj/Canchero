    @Test
    void concurrentBookingsForOverlappingSlotAllowOnlyOneWinner() throws InterruptedException, ExecutionException {
        CountDownLatch ready = new CountDownLatch(2);
        CountDownLatch start = new CountDownLatch(1);
        ExecutorService pool = Executors.newFixedThreadPool(2);

        BookingRequest reqPlayerOne = new BookingRequest(
                "Cancha 1",
                "Complejo Norte",
                "10",
                "101",
                playerOneId.toString(),
                "2026-10-23",
                "18:00 - 20:00",
                240.0,
                "tarjeta",
                List.of(),
                List.of(18, 19),
                "idemp-concurrent-p1");

        // Se solapa en la hora 19:00 - 20:00 con reqPlayerOne
        BookingRequest reqPlayerTwo = new BookingRequest(
                "Cancha 1",
                "Complejo Norte",
                "10",
                "101",
                playerTwoId.toString(),
                "2026-10-23",
                "19:00 - 21:00",
                240.0,
                "tarjeta",
                List.of(),
                List.of(19, 20),
                "idemp-concurrent-p2");

        AtomicInteger successes = new AtomicInteger(0);
        AtomicInteger conflicts = new AtomicInteger(0);

        Callable<Void> taskOne = () -> {
            ready.countDown();
            start.await(5, TimeUnit.SECONDS);
            try {
                service.createBooking(reqPlayerOne, playerOneAuth, "idemp-concurrent-p1");
                successes.incrementAndGet();
            } catch (ResponseStatusException ex) {
                if (ex.getStatusCode().equals(HttpStatus.CONFLICT)) {
                    conflicts.incrementAndGet();
                } else {
                    throw ex;
                }
            }
            return null;
        };

        Callable<Void> taskTwo = () -> {
            ready.countDown();
            start.await(5, TimeUnit.SECONDS);
            try {
                service.createBooking(reqPlayerTwo, playerTwoAuth, "idemp-concurrent-p2");
                successes.incrementAndGet();
            } catch (ResponseStatusException ex) {
                if (ex.getStatusCode().equals(HttpStatus.CONFLICT)) {
                    conflicts.incrementAndGet();
                } else {
                    throw ex;
                }
            }
            return null;
        };

        List<Future<Void>> futures = new ArrayList<>();
        futures.add(pool.submit(taskOne));
        futures.add(pool.submit(taskTwo));

        assertTrue(ready.await(5, TimeUnit.SECONDS));
        start.countDown();

        for (Future<Void> f : futures) {
            f.get();
        }
        pool.shutdownNow();

        assertEquals(1, successes.get(), "Exactamente una solicitud concurrente debe ganar la reserva");
        assertEquals(1, conflicts.get(), "La solicitud concurrente perdedora debe recibir 409 CONFLICT");

        Integer activeReservas = jdbc.queryForObject("select count(*) from reserva where estado = 'A'", Integer.class);
        Integer activePagos = jdbc.queryForObject("select count(*) from pago_reserva where estado = 'A'", Integer.class);
        assertEquals(1, activeReservas);
        assertEquals(1, activePagos);
    }

