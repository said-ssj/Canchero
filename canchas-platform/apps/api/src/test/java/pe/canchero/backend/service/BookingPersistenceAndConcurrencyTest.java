    @Test
    void playerCannotCancelOtherPlayersBooking() {
        BookingRequest req = new BookingRequest(
                "Cancha 1", "Complejo Norte", "10", "101", playerOneId.toString(),
                "2026-10-23", "16:00 - 17:00", 90.0, "tarjeta", List.of(), List.of(16), "idemp-cancel-test",
                "approved", "4532000000004242", "Jugador Uno");
        BookingResponse created = service.createBooking(req, playerOneAuth, "idemp-cancel-test");
        int bookingId = Integer.parseInt(created.id());

        // Jugador Dos intenta cancelar la reserva de Jugador Uno -> 403 FORBIDDEN
        ResponseStatusException forbiddenEx = assertThrows(
                ResponseStatusException.class,
                () -> service.cancelBooking(bookingId, playerTwoAuth));
        assertEquals(HttpStatus.FORBIDDEN, forbiddenEx.getStatusCode());
        assertTrue(forbiddenEx.getReason().contains("No tienes permiso para cancelar esta reserva"));

        // Jugador Uno (propietario de la reserva) la cancela exitosamente
        Optional<BookingResponse> cancelled = service.cancelBooking(bookingId, playerOneAuth);
        assertTrue(cancelled.isPresent());
        assertEquals("Cancelada", cancelled.get().status());
    }
