package pe.canchero.backend.service;

import java.math.BigDecimal;
import java.util.concurrent.Executors;
import org.junit.jupiter.api.*;
import org.springframework.context.annotation.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import org.springframework.web.server.ResponseStatusException;
import pe.canchero.backend.it.PostgresTestServer;
import pe.canchero.backend.it.PostgresTestSupport;
import static org.junit.jupiter.api.Assertions.*;
import static pe.canchero.backend.it.PostgresTestSupport.*;

class PosCatalogPostgresTest {
    AnnotationConfigApplicationContext context;
    PosCatalogService service;
    JdbcTemplate jdbc;
    @Configuration @EnableTransactionManagement
    static class Config {
        @Bean JdbcTemplate jdbc() { return PostgresTestSupport.jdbc(); }
        @Bean DataSourceTransactionManager transactionManager(JdbcTemplate jdbc) { return new DataSourceTransactionManager(jdbc.getDataSource()); }
        @Bean VenueAccessService access(JdbcTemplate jdbc) { return new VenueAccessService(jdbc); }
        @Bean PosCatalogService catalog(JdbcTemplate jdbc, VenueAccessService access) { return new PosCatalogService(jdbc, access); }
    }
    @BeforeEach void setup() {
        PostgresTestServer.requireAvailable();
        PostgresTestServer.resetSchema();
        context = new AnnotationConfigApplicationContext(Config.class);
        service = context.getBean(PosCatalogService.class);
        jdbc = context.getBean(JdbcTemplate.class);
        seedTwoVenues(jdbc);
        jdbc.execute("alter table producto alter column id_producto restart with 100");
        jdbc.execute("alter table categoria_producto alter column id_categoria add generated by default as identity (start with 100)");
    }
    @AfterEach void close() { if (context != null) context.close(); }
    PosCatalogService.ProductRequest product(int category, String code, int stock) {
        return new PosCatalogService.ProductRequest(VENUE_A, category, "Agua mineral", code, "Botella",
                new BigDecimal("600"), "ml", new BigDecimal("1.50"), new BigDecimal("2.50"), stock, 2, "https://example.com/agua.webp");
    }
    @Test void createsPersistentProductAndInitialMovementOnlyInOwnedVenue() {
        var cat = service.createCategory(new PosCatalogService.CategoryRequest(VENUE_A,"Bebidas nuevas","Frías"), OWNER_A);
        int id = service.createProduct(product(cat.id(), "NUEVO-600", 0), OWNER_A);
        var data = new SupabaseDataService(jdbc);
        var saved = data.listProducts(VENUE_A).stream().filter(p -> p.id()==id).findFirst().orElseThrow();
        assertEquals(0, saved.stock());
        assertEquals(0, saved.contenido().compareTo(new BigDecimal("600")));
        assertEquals("ml", saved.unidadMedida());
        assertEquals("https://example.com/agua.webp", saved.fotoUrl());
        assertTrue(data.listProducts(VENUE_B).stream().noneMatch(p -> p.id()==id));
        assertTrue(service.categories(VENUE_B, OWNER_B).stream().noneMatch(c -> c.id()==cat.id()));
        assertEquals(1, jdbc.queryForObject("select count(*) from kardex where id_producto=? and id_sede=?", Integer.class, id, VENUE_A));
    }
    @Test void rejectsForeignVenueAndCategoryWithoutWriting() {
        var foreign = service.createCategory(new PosCatalogService.CategoryRequest(VENUE_B,"Ajena",""), OWNER_B);
        assertThrows(ResponseStatusException.class, () -> service.categories(VENUE_A, OWNER_B));
        assertThrows(ResponseStatusException.class, () -> service.createProduct(product(foreign.id(),"NO",3), OWNER_A));
        assertThrows(ResponseStatusException.class, () -> service.createCategory(new PosCatalogService.CategoryRequest(VENUE_A,"No",""), OWNER_B));
        assertEquals(0, jdbc.queryForObject("select count(*) from producto where codigo_barras='NO'", Integer.class));
    }
    @Test void duplicateSimultaneousCodesCreateOneProductAndMovement() throws Exception {
        int cat = service.categories(VENUE_A, OWNER_A).getFirst().id();
        try (var pool = Executors.newFixedThreadPool(2)) {
            java.util.concurrent.Callable<Boolean> save = () -> {
                try { service.createProduct(product(cat,"SAME",5), OWNER_A); return true; }
                catch (ResponseStatusException ex) { assertEquals(409, ex.getStatusCode().value()); return false; }
            };
            var results = pool.invokeAll(java.util.List.of(save, save));
            assertNotEquals(results.get(0).get(), results.get(1).get());
        }
        assertEquals(1, jdbc.queryForObject("select count(*) from producto where codigo_barras='SAME'", Integer.class));
    }
    @Test void failedInitialMovementRollsBackProductAndRejectsInvalidImages() {
        int cat = service.categories(VENUE_A, OWNER_A).getFirst().id();
        jdbc.execute("""
            create function reject_initial_stock() returns trigger language plpgsql as $$
            begin if NEW.cantidad=13 then raise exception 'Test: stock rejected'; end if; return NEW; end $$;
            create trigger reject_stock before insert on kardex for each row execute function reject_initial_stock();
            """);
        assertThrows(Exception.class, () -> service.createProduct(product(cat,"ROLLBACK",13), OWNER_A));
        assertEquals(0, jdbc.queryForObject("select count(*) from producto where codigo_barras='ROLLBACK'", Integer.class));
        assertThrows(ResponseStatusException.class, () -> PosCatalogService.validatePhoto("javascript:alert(1)"));
        assertThrows(ResponseStatusException.class, () -> PosCatalogService.validatePhoto("data:image/jpeg;base64,AAAA"));
        assertNull(PosCatalogService.validatePhoto(""));
    }
}
