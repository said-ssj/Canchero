    @Test
    void playerCannotConfirmOrCompleteBookings() throws Exception {
        // Interceptor rejects player on confirm
        mvc.perform(patch("/api/bookings/" + booking1Id + "/confirm")
                .header("Authorization", "Bearer " + tokenPlayer1))
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.message").value("No tienes permisos para realizar esta operación"));

        // Interceptor rejects player on complete
        mvc.perform(patch("/api/bookings/" + booking1Id + "/complete")
                .header("Authorization", "Bearer " + tokenPlayer1))
                .andExpect(status().isForbidden())
                .andExpect(jsonPath("$.message").value("No tienes permisos para realizar esta operación"));

        // Verify status unchanged in DB
        Integer statusInDb = jdbc.queryForObject("select id_estado_reserva from reserva where id_reserva = ?", Integer.class, booking1Id);
        assertEquals(1, statusInDb, "El jugador no debe poder confirmar ni completar reservas");
    }

