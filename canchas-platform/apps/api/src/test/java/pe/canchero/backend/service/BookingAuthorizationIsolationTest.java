    @Test
    void anonymousRequestsAreRejectedWith401() throws Exception {
        mvc.perform(get("/api/bookings")).andExpect(status().isUnauthorized());
        mvc.perform(get("/api/bookings/my")).andExpect(status().isUnauthorized());
        mvc.perform(get("/api/bookings/jugador/" + player1Id)).andExpect(status().isUnauthorized());
        mvc.perform(patch("/api/bookings/1/confirm")).andExpect(status().isUnauthorized());
        mvc.perform(patch("/api/bookings/1/complete")).andExpect(status().isUnauthorized());
        mvc.perform(patch("/api/bookings/1/cancel")).andExpect(status().isUnauthorized());
        mvc.perform(post("/api/bookings")
                .contentType(MediaType.APPLICATION_JSON)
                .content("{\"courtId\":\"101\"}")).andExpect(status().isUnauthorized());
    }

