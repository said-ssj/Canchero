    @Test
    void venueOwnerCanConfirmAndCompleteOwnBookings() throws Exception {
        // Owner A confirms Booking 1 (in Sede 10, owned by Owner A)
        mvc.perform(patch("/api/bookings/" + booking1Id + "/confirm")
                .header("Authorization", "Bearer " + tokenOwnerA))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("Confirmada"));

        Integer statusAfterConfirm = jdbc.queryForObject("select id_estado_reserva from reserva where id_reserva = ?", Integer.class, booking1Id);
        assertEquals(2, statusAfterConfirm);

        // Owner A completes Booking 1
        mvc.perform(patch("/api/bookings/" + booking1Id + "/complete")
                .header("Authorization", "Bearer " + tokenOwnerA))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("Completada"));

        Integer statusAfterComplete = jdbc.queryForObject("select id_estado_reserva from reserva where id_reserva = ?", Integer.class, booking1Id);
        assertEquals(3, statusAfterComplete);
    }

