    @Test
    void ownerWithoutVenueIdReturnsOnlyOwnVenues() throws Exception {
        // Owner A owns Sedes 10 and 20; must receive bookings 1 and 2, but NOT booking 3 (Owner B)
        mvc.perform(get("/api/bookings")
                .header("Authorization", "Bearer " + tokenOwnerA))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$", hasSize(2)))
                .andExpect(jsonPath("$[*].id", containsInAnyOrder("1", "2")))
                .andExpect(jsonPath("$[*].venueId", containsInAnyOrder("10", "20")));

        // Owner B owns Sede 30; must receive only booking 3
        mvc.perform(get("/api/bookings")
                .header("Authorization", "Bearer " + tokenOwnerB))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$", hasSize(1)))
                .andExpect(jsonPath("$[0].id").value("3"))
                .andExpect(jsonPath("$[0].venueId").value("30"));
    }

