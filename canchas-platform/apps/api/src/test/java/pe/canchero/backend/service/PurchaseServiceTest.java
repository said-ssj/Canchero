    @Test
    void listsSeedSuppliersAndAllowsCreatingNewSupplier() {
        var suppliers = purchaseService.listSuppliers(1, ownerA, false);
        assertFalse(suppliers.isEmpty());
        assertTrue(suppliers.stream().anyMatch(s -> s.razonSocial().contains("Backus")));

        var req = new SupplierRequest(1, "20555666771", "Distribuidora Lima Norte S.A.C.", "Juan Pérez", "987654321", "juan@limanorte.com", "Av. Túpac Amaru 123");
        var created = purchaseService.createSupplier(req, ownerA);

        assertNotNull(created);
        assertEquals("20555666771", created.ruc());
        assertEquals("Distribuidora Lima Norte S.A.C.", created.razonSocial());

        var updatedList = purchaseService.listSuppliers(1, ownerA, false);
        assertTrue(updatedList.stream().anyMatch(s -> s.id() == created.id()));
    }

    @Test
    void rejectsInvalidRuc() {
        var invalidRuc = new SupplierRequest(1, "12345", "Empresa", null, null, null, null);
        assertThrows(ResponseStatusException.class, () -> purchaseService.createSupplier(invalidRuc, ownerA));
    }

    @Test
    void createsPurchaseOrderAndReceivingIncrementsKardexStock() {
        var items = List.of(new PurchaseItemRequest(10, 24, 2.40));
        var req = new PurchaseRequest(1, 3, "OC-1001", "orden", null, "Pedido quincenal de Sporade", false, items);

        var purchase = purchaseService.createPurchase(req, ownerA);
        assertNotNull(purchase);
        assertEquals("EMITIDA", purchase.estado());
        assertEquals(57.60, purchase.subtotal(), 0.01); // 24 * 2.40 = 57.60

        // Stock in venue 1 is still 10 (not received yet)
        assertEquals(10, posService.listProducts(1).get(0).stock());

        // Now receive the purchase
        var received = purchaseService.receivePurchase(purchase.id(), 1, ownerA);
        assertEquals("RECIBIDA", received.estado());

        // Stock in venue 1 should now be 10 + 24 = 34
        var prods = posService.listProducts(1);
        assertEquals(34, prods.get(0).stock());

        // Kardex has recorded the entry
        var movs = posService.listInventoryMovements(1);
        assertTrue(movs.stream().anyMatch(m -> m.productoId() == 10 && "+".equals(m.tipo()) && m.cantidad() == 24 && m.motivo().contains("Recepción compra")));
    }

    @Test
    void directPurchaseReceiptImmediatelyUpdatesStock() {
        var items = List.of(new PurchaseItemRequest(10, 15, 2.50));
        var req = new PurchaseRequest(1, 1, "F001-9988", "factura", null, "Compra directa en efectivo", true, items);

        var purchase = purchaseService.createPurchase(req, ownerA);
        assertEquals("RECIBIDA", purchase.estado());

        // Immediately updated stock: 10 + 15 = 25
        assertEquals(25, posService.listProducts(1).get(0).stock());
    }

    @Test
    void enforcesTenantIsolationOnPurchasesAndSuppliers() {
        var req = new PurchaseRequest(1, 1, "OC-999", "orden", null, null, false, List.of(new PurchaseItemRequest(10, 5, 2.50)));

        // Owner B trying to list or buy in Sede 1 -> 403 Forbidden
        assertEquals(403, assertThrows(ResponseStatusException.class, () -> controller.purchases(1, ownerB)).getStatusCode().value());
        assertEquals(403, assertThrows(ResponseStatusException.class, () -> controller.suppliers(1, false, ownerB)).getStatusCode().value());
        assertEquals(403, assertThrows(ResponseStatusException.class, () -> controller.createPurchase(req, ownerB)).getStatusCode().value());
    }
