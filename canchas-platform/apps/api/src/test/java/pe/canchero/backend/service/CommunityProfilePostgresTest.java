package pe.canchero.backend.service;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.nio.file.*;
import java.util.*;
import org.junit.jupiter.api.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.web.server.ResponseStatusException;
import pe.canchero.backend.it.*;
import static pe.canchero.backend.it.PostgresTestSupport.*;
import static org.junit.jupiter.api.Assertions.*;

class CommunityProfilePostgresTest {
  JdbcTemplate jdbc; CommunityProfileService service; ObjectMapper json=new ObjectMapper();
  @BeforeEach void setup() throws Exception {
    PostgresTestServer.requireAvailable(); PostgresTestServer.resetSchema();jdbc=PostgresTestSupport.jdbc();seedTwoVenues(jdbc);
    jdbc.execute("alter table usuario add column apellido text");
    jdbc.execute("create table perfil_jugador(id_usuario uuid primary key, foto text, direccion text)");
    jdbc.execute("create table resena(id_resena integer generated by default as identity primary key,id_sede int,id_cliente uuid,puntuacion int,comentario text,fecha_creacion timestamp default now(),estado char(1) default 'A',es_sintetica boolean default false)");
    jdbc.execute(Files.readString(Path.of("../../docs/sql/perfiles_comunidad.sql")));
    service=new CommunityProfileService(jdbc,json);
  }
  @Test void ownerUsesOwnPhotoAndAllOwnedVenuesWithoutAdminGlobalScopeOrPrivateContact() throws Exception {
    jdbc.update("update usuario set id_rol=3,apellido='Apellido',correo='correo-privado@test',telefono='PRIVATEPHONE' where id_usuario=?",OWNER_A_ID);
    jdbc.update("insert into perfil_jugador values(?,'owner-profile-photo','PRIVATEADDRESS')",OWNER_A_ID);
    jdbc.update("update sede set imagen_url='venue-cover' where id_sede=?",VENUE_A);
    jdbc.update("insert into sede(id_sede,id_dueno,nombre,direccion,estado) values(30,?,'Segunda sede','Av. 30','A')",OWNER_A_ID);
    var profile=service.profile(OWNER_A_ID);
    assertEquals("owner-profile-photo",profile.photo());assertEquals(2,profile.venues().size());
    assertTrue(profile.venues().stream().noneMatch(v->v.id().equals("20")));
    assertEquals("",profile.whatsapp());
    String publicJson=json.writeValueAsString(profile);
    assertFalse(publicJson.contains("PRIVATEPHONE"));assertFalse(publicJson.contains("PRIVATEADDRESS"));assertFalse(publicJson.contains("correo-privado"));
    assertEquals(OWNER_A_ID.toString(),service.venueOwner(VENUE_A).id());
    assertEquals("owner-profile-photo",service.venueOwner(VENUE_A).photo());
  }
  @Test void aggregateRatingWeightsEachRealReviewInsteadOfAveragingVenueAverages() {
    jdbc.update("insert into sede(id_sede,id_dueno,nombre,estado) values(30,?,'Segunda sede','A')",OWNER_A_ID);
    for(int score:new int[]{5,5,5})jdbc.update("insert into resena(id_sede,id_cliente,puntuacion,comentario) values(?,?,?,'Opinion')",VENUE_A,CLIENT_1_ID,score);
    jdbc.update("insert into resena(id_sede,id_cliente,puntuacion,comentario) values(30,?,1,'Otra opinion')",CLIENT_1_ID);
    jdbc.update("insert into resena(id_sede,id_cliente,puntuacion,comentario,es_sintetica) values(?,?,1,'Fixture',true)",VENUE_A,CLIENT_1_ID);
    jdbc.update("insert into resena(id_sede,id_cliente,puntuacion,comentario) values(?,?,1,'Sede ajena')",VENUE_B,CLIENT_1_ID);
    var profile=service.profile(OWNER_A_ID);
    assertEquals(4,profile.reviewCount());assertEquals(4d,profile.rating());assertEquals(4,profile.reviews().size());
    assertEquals(0,service.profile(PLAYER_1_ID).reviewCount());
  }
  @Test void playersAndOwnersPublishRealPhotosAndOnlyAuthorCanRemove() throws Exception {
    var image=new java.awt.image.BufferedImage(2,2,java.awt.image.BufferedImage.TYPE_INT_RGB);
    var out=new java.io.ByteArrayOutputStream();javax.imageio.ImageIO.write(image,"jpeg",out);
    String photo="data:image/jpeg;base64,"+Base64.getEncoder().encodeToString(out.toByteArray());
    var post=service.publish(PLAYER_1,"Mi partido",List.of(photo));
    assertEquals(PLAYER_1.id(),post.authorId());assertEquals(photo,service.posts(PLAYER_1_ID,0).items().get(0).photos().get(0));
    assertThrows(ResponseStatusException.class,()->service.deletePost(OWNER_A,UUID.fromString(post.id())));
    assertEquals(1,service.posts(PLAYER_1_ID,0).items().size());
    service.deletePost(PLAYER_1,UUID.fromString(post.id()));assertTrue(service.posts(PLAYER_1_ID,0).items().isEmpty());
    service.publish(OWNER_A,"Promoción",List.of());assertEquals(1,service.profile(OWNER_A_ID).postCount());
    assertThrows(ResponseStatusException.class,()->service.publish(OWNER_A,"",List.of("https://example.test/not-an-upload")));
  }
  @Test void followingIsIdempotentAndSettingsOnlyChangeAuthenticatedUser() {
    service.follow(PLAYER_1,OWNER_A_ID,true);service.follow(PLAYER_1,OWNER_A_ID,true);
    assertEquals(1,service.profile(OWNER_A_ID).followers());assertTrue(service.following(PLAYER_1,OWNER_A_ID));
    assertThrows(ResponseStatusException.class,()->service.follow(OWNER_A,OWNER_A_ID,true));
    service.follow(PLAYER_1,OWNER_A_ID,false);assertEquals(0,service.profile(OWNER_A_ID).followers());
    service.saveSettings(OWNER_A,new CommunityProfileService.Settings("Mis complejos","+51 999111222",null));
    assertEquals("51999111222",service.profile(OWNER_A_ID).whatsapp());assertEquals("Mis complejos",service.profile(OWNER_A_ID).biography());
    assertEquals("",service.profile(OWNER_B_ID).whatsapp());assertEquals("",service.profile(OWNER_B_ID).biography());
    assertThrows(ResponseStatusException.class,()->service.saveSettings(PLAYER_1,new CommunityProfileService.Settings("Bio","numero-invalido",null)));
  }
}
