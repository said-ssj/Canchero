-- Migración para Reporte de Incidencias en Canchas
-- Permite que los jugadores reporten problemas específicos de una cancha (iluminación, césped, redes, etc.).
-- La sede vinculada recibe automáticamente el reporte y puede tener múltiples incidencias de sus diferentes canchas.

BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '30s';

CREATE TABLE IF NOT EXISTS public.reporte_cancha (
    id_reporte integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cancha integer NOT NULL REFERENCES public.cancha(id_cancha) ON DELETE CASCADE,
    id_sede integer NOT NULL REFERENCES public.sede(id_sede) ON DELETE CASCADE,
    id_usuario uuid NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
    tipo_problema varchar(50) NOT NULL, -- ILUMINACION, ESTADO_CESPED, REDES_ARCOS, LIMPIEZA, HORARIO_CONFLICTO, OTRO
    descripcion text NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE', -- PENDIENTE, EN_REVISION, RESUELTO, DESCARTADO
    prioridad varchar(20) NOT NULL DEFAULT 'MEDIA', -- BAJA, MEDIA, ALTA, URGENTE
    resolucion text,
    fecha_resolucion timestamp without time zone,
    id_usuario_resolucion uuid REFERENCES public.usuario(id_usuario),
    fecha_creacion timestamp without time zone NOT NULL DEFAULT now(),
    usucre varchar(40) DEFAULT 'API',
    pccre varchar(40) DEFAULT 'SPRING',
    feccre timestamp without time zone NOT NULL DEFAULT now(),
    usmod varchar(40),
    pcmod varchar(40),
    fecmod timestamp without time zone
);

CREATE INDEX IF NOT EXISTS idx_reporte_cancha_sede ON public.reporte_cancha(id_sede, fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS idx_reporte_cancha_cancha ON public.reporte_cancha(id_cancha, fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS idx_reporte_cancha_usuario ON public.reporte_cancha(id_usuario, fecha_creacion DESC);
CREATE INDEX IF NOT EXISTS idx_reporte_cancha_estado ON public.reporte_cancha(id_sede, estado);

COMMIT;

