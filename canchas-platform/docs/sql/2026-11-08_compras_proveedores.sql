-- ============================================================================
-- CANCHERO: MÓDULO DE COMPRAS Y PROVEEDORES
-- Tablas para directorio de proveedores, órdenes de compra y recepción de mercadería.
-- Compatible con PostgreSQL y multi-tenant por sede.
-- ============================================================================

CREATE TABLE IF NOT EXISTS proveedor (
    id_proveedor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sede integer REFERENCES sede(id_sede) ON DELETE SET NULL,
    ruc varchar(11) NOT NULL,
    razon_social varchar(150) NOT NULL,
    contacto varchar(100),
    telefono varchar(20),
    correo varchar(100),
    direccion varchar(200),
    estado char(1) NOT NULL DEFAULT 'A',
    feccre timestamp without time zone NOT NULL DEFAULT now(),
    fecmod timestamp without time zone
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_proveedor_ruc_sede ON proveedor (id_sede, ruc) WHERE estado = 'A';
CREATE INDEX IF NOT EXISTS idx_proveedor_sede ON proveedor (id_sede, estado);

CREATE TABLE IF NOT EXISTS compra (
    id_compra integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sede integer NOT NULL REFERENCES sede(id_sede),
    id_proveedor integer NOT NULL REFERENCES proveedor(id_proveedor),
    numero_comprobante varchar(50) NOT NULL,
    tipo_comprobante varchar(20) NOT NULL DEFAULT 'factura', -- factura, boleta, guia, orden
    fecha_emision timestamp without time zone NOT NULL DEFAULT now(),
    fecha_entrega_estimada timestamp without time zone,
    fecha_recepcion timestamp without time zone,
    subtotal numeric(12,2) NOT NULL DEFAULT 0,
    igv numeric(12,2) NOT NULL DEFAULT 0,
    total numeric(12,2) NOT NULL DEFAULT 0,
    estado varchar(20) NOT NULL DEFAULT 'BORRADOR', -- BORRADOR, EMITIDA, RECIBIDA, ANULADA
    observacion varchar(300),
    usucre varchar(40),
    feccre timestamp without time zone NOT NULL DEFAULT now(),
    fecmod timestamp without time zone
);

CREATE INDEX IF NOT EXISTS idx_compra_sede_fecha ON compra (id_sede, fecha_emision DESC);
CREATE INDEX IF NOT EXISTS idx_compra_proveedor ON compra (id_proveedor);

CREATE TABLE IF NOT EXISTS compra_detalle (
    id_compra_detalle integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_compra integer NOT NULL REFERENCES compra(id_compra) ON DELETE CASCADE,
    id_producto integer NOT NULL REFERENCES producto(id_producto),
    cantidad integer NOT NULL,
    costo_unitario numeric(10,2) NOT NULL,
    subtotal numeric(12,2) NOT NULL,
    estado char(1) NOT NULL DEFAULT 'A',
    feccre timestamp without time zone NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_compra_detalle_compra ON compra_detalle (id_compra);
