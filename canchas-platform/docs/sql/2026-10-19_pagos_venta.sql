-- Serializa pagos y cierre sobre la misma fila del turno.
CREATE FUNCTION public.validar_pago_venta()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE turno integer; venta_activa char(1); metodo text; abierto boolean;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'Los pagos guardados son inmutables; una devolucion requiere su propio contrato' USING ERRCODE='23514';
    END IF;
    SELECT v.id_sesion_caja,v.estado INTO turno,venta_activa FROM public.venta v WHERE v.id_venta=NEW.id_venta;
    IF turno IS NULL OR venta_activa <> 'A' THEN
        RAISE EXCEPTION 'La venta requiere un turno activo' USING ERRCODE='23514';
    END IF;
    SELECT sc.estado='A' AND sc.fecha_cierre IS NULL INTO abierto
      FROM public.sesion_caja sc WHERE sc.id_sesion_caja=turno FOR UPDATE;
    IF abierto IS DISTINCT FROM true THEN
        RAISE EXCEPTION 'El turno esta cerrado' USING ERRCODE='23514';
    END IF;
    SELECT lower(btrim(mp.nombre)) INTO metodo FROM public.metodo_pago mp
     WHERE mp.id_metodo_pago=NEW.id_metodo_pago AND mp.estado='A';
    IF metodo = U&'tarjeta d\00e9bito/cr\00e9dito' THEN metodo := 'tarjeta'; END IF;
    IF metodo IS NULL OR metodo NOT IN ('efectivo','tarjeta','yape','plin') THEN
        RAISE EXCEPTION 'Medio de pago no disponible' USING ERRCODE='23514';
    END IF;
    IF metodo <> 'efectivo' AND NEW.monto_recibido <> NEW.monto THEN
        RAISE EXCEPTION 'Un pago digital no genera vuelto' USING ERRCODE='23514';
    END IF;
    IF NEW.estado <> 'A' THEN RAISE EXCEPTION 'El pago nuevo debe estar activo' USING ERRCODE='23514'; END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER venta_pago_validar BEFORE INSERT OR UPDATE OR DELETE ON public.venta_pago
FOR EACH ROW EXECUTE FUNCTION public.validar_pago_venta();

-- La suma se comprueba al COMMIT para permitir varios medios en la misma transaccion.
CREATE FUNCTION public.validar_total_pagado_venta()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
DECLARE venta_id integer; acordado numeric; cobrado numeric;
BEGIN
    venta_id := NEW.id_venta;
    SELECT total INTO acordado FROM public.venta WHERE id_venta=venta_id;
    SELECT coalesce(sum(monto),0) INTO cobrado FROM public.venta_pago WHERE id_venta=venta_id AND estado='A';
    IF cobrado <> acordado THEN
        RAISE EXCEPTION 'El desglose no coincide con el total de la venta' USING ERRCODE='23514';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER venta_pago_total AFTER INSERT ON public.venta_pago
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION public.validar_total_pagado_venta();

CREATE FUNCTION public.proteger_total_venta_pagada()
RETURNS trigger LANGUAGE plpgsql SET search_path = pg_catalog, public AS $$
BEGIN
    IF NEW.total IS DISTINCT FROM OLD.total AND EXISTS (SELECT 1 FROM public.venta_pago WHERE id_venta=OLD.id_venta) THEN
        RAISE EXCEPTION 'No se modifica el total de una venta con pagos; requiere contrato de devolucion' USING ERRCODE='23514';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER venta_total_protegido BEFORE UPDATE ON public.venta
FOR EACH ROW EXECUTE FUNCTION public.proteger_total_venta_pagada();

