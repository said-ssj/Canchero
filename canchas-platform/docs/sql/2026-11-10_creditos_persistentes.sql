-- Cuentas por cobrar y abonos persistidos por sede.
BEGIN;

CREATE TABLE cuenta_por_cobrar (
    id_cuenta integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sede integer NOT NULL REFERENCES sede(id_sede) ON DELETE RESTRICT,
    cliente_nombre varchar(160) NOT NULL,
    cliente_documento varchar(30) NOT NULL DEFAULT '',
    telefono varchar(30) NOT NULL DEFAULT '',
    equipo varchar(120) NOT NULL DEFAULT '',
    monto_original numeric(12,2) NOT NULL CHECK (monto_original > 0),
    saldo numeric(12,2) NOT NULL CHECK (saldo >= 0),
    total_abonado numeric(12,2) NOT NULL DEFAULT 0 CHECK (total_abonado >= 0),
    concepto varchar(300) NOT NULL,
    fecha_emision timestamp without time zone NOT NULL DEFAULT now(),
    fecha_vencimiento date NOT NULL,
    estado varchar(20) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'CANCELADA')),
    usucre varchar(40),
    pccre varchar(40),
    feccre timestamp without time zone NOT NULL DEFAULT now(),
    usmod varchar(40),
    pcmod varchar(40),
    fecmod timestamp without time zone,
    CONSTRAINT cuenta_por_cobrar_saldo_chk CHECK (saldo + total_abonado = monto_original)
);

CREATE TABLE abono_credito (
    id_abono integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cuenta integer NOT NULL REFERENCES cuenta_por_cobrar(id_cuenta) ON DELETE RESTRICT,
    id_sesion_caja integer REFERENCES sesion_caja(id_sesion_caja) ON DELETE SET NULL,
    fecha_abono timestamp without time zone NOT NULL DEFAULT now(),
    monto numeric(12,2) NOT NULL CHECK (monto > 0),
    medio_pago varchar(40) NOT NULL,
    nro_operacion varchar(120),
    observacion varchar(300),
    cajero_nombre varchar(120) NOT NULL,
    usucre varchar(40),
    pccre varchar(40),
    feccre timestamp without time zone NOT NULL DEFAULT now()
);

CREATE INDEX cuenta_por_cobrar_sede_fecha_idx
    ON cuenta_por_cobrar (id_sede, fecha_emision DESC, id_cuenta DESC);
CREATE INDEX abono_credito_cuenta_fecha_idx
    ON abono_credito (id_cuenta, fecha_abono DESC, id_abono DESC);
CREATE INDEX abono_credito_sesion_idx
    ON abono_credito (id_sesion_caja) WHERE id_sesion_caja IS NOT NULL;

COMMIT;
