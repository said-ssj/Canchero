CREATE TABLE public.resena (
    id_resena integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sede integer NOT NULL REFERENCES public.sede(id_sede) ON DELETE RESTRICT,
    id_cliente uuid NOT NULL REFERENCES public.cliente(id_cliente) ON DELETE RESTRICT,
    id_reserva integer NOT NULL REFERENCES public.reserva(id_reserva) ON DELETE RESTRICT,
    puntuacion smallint NOT NULL,
    comentario text NOT NULL,
    es_sintetica boolean NOT NULL DEFAULT false,
    estado char(1) NOT NULL DEFAULT 'A',
    -- Compatibilidad con el DTO JDBC actual, que utiliza LocalDateTime.
    fecha_creacion timestamp without time zone NOT NULL DEFAULT timezone('America/Lima', now()),
    usucre varchar(100) NOT NULL DEFAULT 'API',
    pccre varchar(100) NOT NULL DEFAULT 'SPRING',
    feccre timestamp without time zone NOT NULL DEFAULT timezone('America/Lima', now()),
    usmod varchar(100),
    pcmod varchar(100),
    fecmod timestamp without time zone,
    CONSTRAINT resena_una_por_reserva UNIQUE (id_reserva),
    CONSTRAINT resena_puntuacion_valida CHECK (puntuacion BETWEEN 1 AND 5),
    CONSTRAINT resena_comentario_valido CHECK (char_length(btrim(comentario)) BETWEEN 1 AND 2000),
    CONSTRAINT resena_estado_valido CHECK (estado IN ('A', 'I', 'T')),
    -- El listado publico actual solo consulta estado A: no publicar fixtures.
    CONSTRAINT resena_sintetica_no_publica CHECK (NOT es_sintetica OR estado = 'T')
);

CREATE INDEX resena_sede_publica_fecha_idx
    ON public.resena (id_sede, fecha_creacion DESC)
    WHERE estado = 'A' AND NOT es_sintetica;

CREATE INDEX resena_cliente_idx ON public.resena (id_cliente);

-- Impide vincular una reserva a otra sede/cliente o calificar sin finalizar.
-- No sustituye comprobar en la API quien es el usuario que envia la peticion.
CREATE FUNCTION public.validar_relacion_resena()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
    cliente_reserva uuid;
    sede_reserva integer;
    estado_reserva_nombre text;
BEGIN
    SELECT r.id_cliente, c.id_sede, er.nombre
      INTO cliente_reserva, sede_reserva, estado_reserva_nombre
      FROM public.reserva r
      JOIN public.cancha c ON c.id_cancha = r.id_cancha
      JOIN public.sede s ON s.id_sede = c.id_sede
      JOIN public.estado_reserva er ON er.id_estado_reserva = r.id_estado_reserva
     WHERE r.id_reserva = NEW.id_reserva
       AND r.estado = 'A' AND c.estado = 'A'
       AND s.estado = 'A' AND er.estado = 'A'
     FOR SHARE OF r, c, s, er;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'La reserva o su recinto no estan activos' USING ERRCODE = '23514';
    END IF;
    IF lower(btrim(estado_reserva_nombre)) <> 'completada' THEN
        RAISE EXCEPTION 'Solo se califican reservas completadas' USING ERRCODE = '23514';
    END IF;
    IF NEW.id_cliente IS DISTINCT FROM cliente_reserva
       OR NEW.id_sede IS DISTINCT FROM sede_reserva THEN
        RAISE EXCEPTION 'La resena no corresponde al cliente y sede de la reserva' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER resena_validar_relacion
    BEFORE INSERT OR UPDATE OF id_reserva, id_cliente, id_sede
    ON public.resena
    FOR EACH ROW EXECUTE FUNCTION public.validar_relacion_resena();

